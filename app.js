const $view = () => document.getElementById("view");
let META = null;
const packCache = new Map();
let lexCache = null, searchCache = null;
let trailMode = "push";

const store = {
  get notes() { try { return JSON.parse(localStorage.getItem("bs-notes") || "{}"); } catch { return {}; } },
  set notes(v) { localStorage.setItem("bs-notes", JSON.stringify(v)); },
  get trans() { return localStorage.getItem("bs-trans") || "web"; },
  set trans(v) { localStorage.setItem("bs-trans", v); },
  get path() { try { return JSON.parse(localStorage.getItem("bs-path") || "[]"); } catch { return []; } },
  set path(v) { localStorage.setItem("bs-path", JSON.stringify(v.slice(-40))); },
  set last(v) { localStorage.setItem("bs-last", JSON.stringify(v)); },
  get last() { try { return JSON.parse(localStorage.getItem("bs-last") || "null"); } catch { return null; } }
};

function esc(s) {
  return String(s ?? "").replace(/[&<>"']/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
}
function bookMeta(slug) { return META.books.find(b => b.slug === slug); }
function refLabel(slug, ch, vs) {
  const b = bookMeta(slug);
  return `${b ? b.name : slug} ${ch}${vs ? ":" + vs : ""}`;
}
const NOTE_TEMPLATE = "Verse:\n\nDesign:\n\nDevelopment:\n\nActions:\n\nOutcome:\n";
function noteHasContent(text) {
  const rest = text.replace(/^(Verse|Design|Development|Actions|Outcome):/gm, "").trim();
  return rest.length > 0;
}
function verseNoteKey(slug, ch, vs) { return `v|${slug}|${ch}|${vs}`; }
function wordNoteKey(slug, ch, vs, strongs) { return `w|${slug}|${ch}|${vs}|${strongs}`; }

async function loadJSON(url) {
  const r = await fetch(url);
  if (!r.ok) throw new Error(`Failed to load ${url}`);
  return r.json();
}
async function loadMeta() { if (!META) META = await loadJSON("data/meta.json"); return META; }
async function loadBook(slug) {
  if (!packCache.has(slug)) packCache.set(slug, await loadJSON(`data/${slug}.json`));
  return packCache.get(slug);
}
async function loadLex() { if (!lexCache) lexCache = await loadJSON("data/lexicon.json"); return lexCache; }
async function loadSearch() { if (!searchCache) searchCache = await loadJSON("data/search.json"); return searchCache; }
function getVerse(pack, ch, vs) {
  const arr = pack.verses[String(ch)] || [];
  return arr.find(v => v.n === vs) || null;
}

function setTab(name) {
  document.querySelectorAll("#tabs a").forEach(a =>
    a.classList.toggle("active", a.dataset.tab === name));
}
function loading() { $view().innerHTML = `<p class="loading">Loading…</p>`; }

/* ---------------- path trail ---------------- */

function pushPath(slug, ch, vs) {
  const p = store.path;
  const cur = { slug, ch, vs };
  const lastIt = p[p.length - 1];
  if (!lastIt || lastIt.slug !== slug || lastIt.ch !== ch || lastIt.vs !== vs) {
    p.push(cur); store.path = p;
  }
}
function jumpPath(idx) {
  const p = store.path;
  const target = p[idx];
  store.path = p.slice(0, idx + 1);
  trailMode = "jump";
  location.hash = `#/study/${target.slug}/${target.ch}/${target.vs}`;
}
function pathHTML(curSlug, curCh, curVs) {
  const p = store.path;
  if (!p.length) return "";
  const chips = p.map((it, i) => {
    const cur = it.slug === curSlug && it.ch === curCh && it.vs === curVs && i === p.length - 1;
    return `<button class="crumb${cur ? " cur" : ""}" data-path="${i}">${esc(refLabel(it.slug, it.ch, it.vs))}</button>`;
  }).join(" ");
  return `<div class="path"><span class="lbl">Your path</span>${chips}
    <button class="clear" id="path-clear">clear</button></div>`;
}
function wirePath() {
  document.querySelectorAll("[data-path]").forEach(b =>
    b.addEventListener("click", () => jumpPath(+b.dataset.path)));
  const c = document.getElementById("path-clear");
  if (c) c.addEventListener("click", () => { store.path = []; render(); });
}

