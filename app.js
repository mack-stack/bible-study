function buildAliasMap() {
  const map = {};
  for (const slug of Object.keys(BOOK_ALIASES))
    for (const a of BOOK_ALIASES[slug]) map[a] = { slug, ot: false };
  for (const slug of Object.keys(OT_ALIASES))
    for (const a of OT_ALIASES[slug]) if (!map[a]) map[a] = { slug, ot: true };
  return map;
}
const ALIAS_MAP = buildAliasMap();
const SINGLE_CHAPTER = { "philemon": 1, "2-john": 1, "3-john": 1, "jude": 1, "obadiah": 1 };

/* booksMeta: [{slug, name, chapters}] used for chapter validation */
function parseReference(raw, booksMeta) {
  if (!raw || !raw.trim()) return { error: "Type a reference, like Romans 8:28." };
  let t = raw.toLowerCase().trim().replace(/\s+/g, " ");
  // range: keep the start verse
  const dash = t.search(/\d\s*-\s*\d/);
  if (dash >= 0) t = t.slice(0, dash + 1).trim();

  const bySlug = {};
  for (const b of booksMeta) bySlug[b.slug] = b;

  function finish(bookPart, n1, n2) {
    const hit = ALIAS_MAP[bookPart.replace(/\s+/g, "")];
    if (!hit) return null;
    if (hit.ot) return { ot: true, slug: hit.slug };
    const meta = bySlug[hit.slug];
    if (!meta) return null;
    let ch = 1, vs = null;
    if (n1 != null && n2 != null) { ch = n1; vs = n2; }
    else if (n1 != null) {
      if (SINGLE_CHAPTER[hit.slug] && meta.chapters === 1) { ch = 1; vs = n1; }
      else ch = n1;
    }
    if (ch < 1 || ch > meta.chapters)
      return { error: `${meta.name} has ${meta.chapters} chapter${meta.chapters > 1 ? "s" : ""}.` };
    if (vs != null && vs < 1) return { error: "Verse numbers start at 1." };
    return { slug: hit.slug, ch, vs };
  }

  // spaced form: "<book> <ch>:<vs>" / "<book> <ch>" / "<book>"
  let m = t.match(/^(.+?)\s+(\d+)\s*[:.]\s*(\d+)$/);
  if (m) { const r = finish(m[1], +m[2], +m[3]); if (r) return r; }
  m = t.match(/^(.+?)\s+(\d+)$/);
  if (m) { const r = finish(m[1], +m[2], null); if (r) return r; }
  m = t.match(/^(\D+)$/);
  if (m) { const r = finish(m[1], null, null); if (r) return r; }

  // squashed form: "1tim2:12", "rom8:28", "jn3"
  const sq = t.replace(/\s+/g, "");
  const aliases = Object.keys(ALIAS_MAP).sort((a, b) => b.length - a.length);
  for (const a of aliases) {
    if (!sq.startsWith(a)) continue;
    const rest = sq.slice(a.length);
    const rm = rest.match(/^(\d+)(?:[:.](\d+))?$/);
    if (rm || rest === "") {
      const r = finish(a, rm ? +rm[1] : null, rm && rm[2] ? +rm[2] : null);
      if (r) return r;
    }
  }

  // suggestions: books sharing a prefix with the first word typed
  const firstWord = t.split(" ")[0].replace(/^\d/, "");
  const sugg = [];
  for (const b of booksMeta) {
    const base = b.name.toLowerCase().replace(/^\d+\s/, "");
    if (firstWord && base.startsWith(firstWord.slice(0, 4))) sugg.push(b);
  }
  return { error: "Could not read that reference.", suggestions: sugg.slice(0, 4) };
}

