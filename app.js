async function render() {
  await loadMeta();
  const hash = location.hash.replace(/^#\/?/, "");
  const parts = hash.split("/").filter(Boolean);
  try {
    if (parts.length === 0) return viewHome();
    if (parts[0] === "read" && parts[1]) return viewRead(parts[1], Math.max(1, +parts[2] || 1));
    if (parts[0] === "study" && parts[1]) return viewStudy(parts[1], +parts[2] || 1, +parts[3] || 1);
    if (parts[0] === "search") return viewSearch();
    if (parts[0] === "maps") return viewMaps();
    if (parts[0] === "context") return viewContext();
    if (parts[0] === "about") return viewAbout();
    return viewHome();
  } catch (e) {
    $view().innerHTML = `<p class="err">Something failed to load (${esc(e.message)}).
      If you are opening this from a file, serve the folder over http instead; browsers block data files on file:// pages.</p>`;
  }
}

function wireLookup() {
  const form = document.getElementById("lookup-form");
  const input = document.getElementById("lookup-input");
  const msg = document.getElementById("lookup-msg");
  const dl = document.getElementById("book-list");
  if (META) dl.innerHTML = META.books.map(b => `<option value="${esc(b.name)} ">`).join("");
  form.addEventListener("submit", e => {
    e.preventDefault();
    msg.innerHTML = "";
    const r = parseReference(input.value, META.books);
    if (r.error) {
      msg.innerHTML = `${esc(r.error)}${(r.suggestions || []).length
        ? " Try: " + r.suggestions.map(b => `<a href="#" data-sugg="${esc(b.name)} 1:1">${esc(b.name)}</a>`).join(", ")
        : ""}`;
      msg.querySelectorAll("[data-sugg]").forEach(a => a.addEventListener("click", ev => {
        ev.preventDefault(); input.value = a.dataset.sugg; form.dispatchEvent(new Event("submit"));
      }));
      return;
    }
    if (r.ot) {
      msg.textContent = "That is an Old Testament book. This prototype covers the New Testament; the Old Testament gets its own pass later.";
      return;
    }
    input.value = "";
    trailMode = "push";
    if (r.vs) location.hash = `#/study/${r.slug}/${r.ch}/${r.vs}`;
    else location.hash = `#/read/${r.slug}/${r.ch}`;
    if (location.hash === `#/study/${r.slug}/${r.ch}/${r.vs}` || location.hash === `#/read/${r.slug}/${r.ch}`) render();
  });
}

async function boot() {
  await loadMeta();
  wireLookup();
  window.addEventListener("hashchange", render);
  render();
  if ("serviceWorker" in navigator) {
    navigator.serviceWorker.register("sw.js").catch(() => {});
  }
}

if (typeof document !== "undefined") {
  if (document.readyState === "loading") document.addEventListener("DOMContentLoaded", boot);
  else boot();
}
